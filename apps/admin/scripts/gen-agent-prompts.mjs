// Regenerates lib/content-agents/prompts.ts from the brief.
//
// The hundred prompts are the client's text, not ours. Retyping them is how a
// rule quietly changes meaning, so they are parsed out of the two markdown
// files at the repo root and written as one generated module. Edit the markdown
// and re-run this; never hand-edit prompts.ts.
//
// Run:  node scripts/gen-agent-prompts.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(here, "../../..");          // apps/admin/scripts → repo root
const OUT = resolve(here, "../lib/content-agents/prompts.ts");

const master = readFileSync(`${REPO}/finuer_agents_master_rules.md`, "utf8");
const all = readFileSync(`${REPO}/finuer_agents_all_100.md`, "utf8");

// Master rules: everything after the H1 line, up to the trailing rule.
const masterBody = master.replace(/^# .*\n/, "").replace(/\n---\s*$/, "").trim();

// Agent blocks: "### A001 — NAME", then its labelled lines until the next heading.
const marks = [];
const re = /^### (A\d{3}) — (.+)$/gm;
let m;
while ((m = re.exec(all)) !== null) {
  marks.push({ id: m[1], name: m[2].trim(), start: m.index + m[0].length });
}

const blocks = marks.map((mark, i) => {
  const end = i + 1 < marks.length ? all.lastIndexOf("### ", marks[i + 1].start) : all.length;
  return {
    no: Number(mark.id.slice(1)),
    id: mark.id,
    name: mark.name,
    body: all.slice(mark.start, end).trim(),
  };
});

/*
 * Checked here rather than at runtime.
 *
 * A block that was cut short, or that swallowed the one after it, still reads
 * like a prompt — the writer would simply follow half a brief, and nothing in
 * the feed would say so. Cheaper to refuse to generate.
 */
if (blocks.length !== 100) throw new Error(`expected 100 blocks, got ${blocks.length}`);
for (const b of blocks) {
  if (!b.body.includes("NEVER:")) throw new Error(`${b.id}: block looks truncated`);
  if (/^### /m.test(b.body)) throw new Error(`${b.id}: block bled into the next one`);
  // The brief forbids any system label reaching a post, so the A-number and the
  // desk heading are deliberately left out of the prompt text.
  if (b.body.includes(b.id)) throw new Error(`${b.id}: block body repeats its own label`);
}

const lit = (s) =>
  "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

const out = `/**
 * The brief, verbatim.
 *
 * Generated by scripts/gen-agent-prompts.mjs from finuer_agents_master_rules.md
 * and finuer_agents_all_100.md at the repo root — the two files the brief
 * arrived in. Nothing here is edited by hand: the text is the contract, and
 * retyping a hundred blocks is how a rule quietly changes meaning. Edit the
 * markdown and regenerate.
 *
 * MASTER_RULES is composed into every prompt at generation time rather than
 * stored per agent, so one edit reaches all hundred writers. AGENT_PROMPTS holds
 * each agent's own block; the heading and its A-number are left out on purpose,
 * because the brief forbids any system label reaching a published post.
 */

export const MASTER_RULES = ${lit(masterBody)};

export const AGENT_PROMPTS: Record<number, string> = {
${blocks.map(b => `  // ${b.id} — ${b.name}\n  ${b.no}: ${lit(b.body)},`).join("\n")}
};

/** The brief's own names for the hundred desks, for logs and admin, never a post. */
export const AGENT_BEATS: Record<number, string> = {
${blocks.map(b => `  ${b.no}: ${JSON.stringify(b.name)},`).join("\n")}
};
`;

writeFileSync(OUT, out, "utf8");
console.log(`wrote ${OUT}`);
console.log(`${blocks.length} blocks, master rules ${masterBody.length} chars, ` +
  `prompt chars ${Math.min(...blocks.map(b => b.body.length))}–${Math.max(...blocks.map(b => b.body.length))}`);
